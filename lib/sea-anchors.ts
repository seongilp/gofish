/**
 * 해역별 바다상태 아이콘을 얹을 **바다 위 대표 좌표**.
 *
 * 왜 손으로 고르나: 해역 경계 폴리곤을 새로 구해 중심을 계산하는 건 과하다(아이콘 4개다).
 * 대신 각 해역의 **먼바다** 한 점을 직접 골랐다. 두 가지를 지킨다 —
 *  (1) 육지에 얹히지 않게: 전부 열린 바다 좌표다.
 *  (2) 낚시터 49개 마커를 가리지 않게: 마커는 해안선을 따라 있으니 그보다 바깥쪽 바다에 둔다.
 * 초기 fitBounds 상자(125.086~130.914 E, 33.238~38.45 N) 안에 들어오는 값만 썼다 —
 * 밖에 두면 기본 화면에서 안 보인다.
 */
export const SEA_ANCHORS: Record<Region, [number, number]> = {
  서해: [125.35, 36.2], // 태안 서쪽 열린 황해
  남해: [128.05, 34.0], // 통영·남해도 남쪽 열린 바다
  동해: [130.2, 37.55], // 강릉·속초 동쪽 열린 동해(울릉도 마커와 겹치지 않게 북서로)
  제주: [125.8, 33.45], // 제주 서쪽 열린 바다(제주 지점 클러스터를 가리지 않게 서쪽으로)
};

/**
 * 파고에 따라 물결 이모지 크기를 연속적으로 키운다.
 *
 * **단계로 "위험/안전" 을 규정하지 않는다.** 잔잔하면 작게, 거칠면 크게 — 크기는
 * 연속값이라 임의의 경계가 없다. 규모의 정확한 판단은 함께 적는 숫자가 맡는다.
 * 16px(하한)~34px(상한) 사이로 자른다.
 */
export function waveGlyphSize(waveMaxM: number | null): number {
  if (waveMaxM === null) return 18;
  return Math.max(16, Math.min(34, 16 + waveMaxM * 6));
}
